#!/usr/bin/env node
// =============================================================================
// file_id: SOM-SCR-0046-v0.0.1
// name: codebook-to-profile.mjs
// description: Bridges a colloquy codebook persona markdown file into a Hermes
//              CLI profile at ~/.hermes/profiles/<vault_name>/. Extracts the
//              Role + Operating Principles sections into SOUL.md (becomes the
//              system prompt, gets position-0 KV-cache for free every turn).
//              Stamps config.yaml + .env pointing at the local Ollama endpoint
//              and the canonical codebook. Idempotent. Safe to re-run.
// category: SCR
// tags: [colloquy, hermes, profile, bridge, ollama]
// created: 2026-04-22
// version: 0.0.1
// =============================================================================
//
// Usage:
//   node codebook-to-profile.mjs --persona persona-voxel-v1 --vault voxel
//   node codebook-to-profile.mjs --persona persona-vertex-v1 --vault vertex
//   node codebook-to-profile.mjs --persona persona-vector-v1 --vault vector_07 \
//        --agent-uuid <uuid>   # stamps agent_uuid into .env for lineage
//   node codebook-to-profile.mjs --all    # bridge every known persona
//
// What this produces at ~/.hermes/profiles/<vault>/:
//   SOUL.md         # Role + Principles from codebook (position-0 system prompt)
//   config.yaml     # model provider, base_url, context, auxiliary blocks
//   .env            # HERMES_HOME, COLLOQUY_*, model choice
// =============================================================================
import { existsSync, readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { homedir } from 'node:os';

const HERMES_HOME_ROOT = `${homedir()}/.hermes/profiles`;

const PERSONAS_DIRS = [
  `${homedir()}/openclaw/skills/colloquy/personas`,
  `${homedir()}/.claude/skills/colloquy/personas`,
  'D:/somacosf/.claude/skills/colloquy/personas',
];

function findPersonaFile(name) {
  for (const d of PERSONAS_DIRS) {
    const p = path.join(d, `${name}.md`);
    if (existsSync(p)) return p;
  }
  return null;
}

// ---------- model defaults per persona (overridable via env) ------------------
const MODEL_DEFAULTS = {
  'persona-voxel-v1':  process.env.VOXEL_MODEL  ?? 'qwen2.5:7b',   // transport, small is fine
  'persona-hermes-v1': process.env.VOXEL_MODEL  ?? 'qwen2.5:7b',   // legacy alias
  'persona-vertex-v1': process.env.VERTEX_MODEL ?? 'qwen2.5:14b',  // memory work needs quality
  'persona-vector-v1': process.env.VECTOR_MODEL ?? 'qwen2.5:7b',   // cheap/fast per-task
  'persona-openclaw-v1': process.env.OPENCLAW_MODEL ?? 'qwen2.5:7b',
};

const OLLAMA_BASE_URL = process.env.OLLAMA_BASE_URL ?? 'http://localhost:11434/v1';

// ---------- extract SOUL.md from codebook markdown ----------------------------
function extractSoul(markdown, vaultName) {
  // Split on YAML frontmatter fences
  const m = markdown.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  const body = m ? m[2] : markdown;

  // Pull out Role + Operating Principles + (Identity Anchor as context)
  const sections = {};
  const re = /^## ([^\n]+)\n([\s\S]*?)(?=\n## |\n# |$)/gm;
  let match;
  while ((match = re.exec(body)) !== null) {
    sections[match[1].trim()] = match[2].trim();
  }

  const want = ['Role', 'Identity Anchor', 'Operating Principles', 'Witness Policy', 'Tool Budget'];
  const parts = [];
  for (const s of want) if (sections[s]) parts.push(`## ${s}\n\n${sections[s]}`);

  return (
`# ${vaultName}

${parts.join('\n\n')}

---

## Runtime Context

You are running inside a Hermes CLI profile named \`${vaultName}\`. Your codebook anchors the persona; this profile provides session, memory, and gateway isolation. You are parented to Openclaw on this host and share the local Ollama endpoint with other local agents. Use the colloquy heartbeat stream (via libsql) for cross-agent coordination, not out-of-band messaging.
`);
}

// ---------- config.yaml generator ---------------------------------------------
function configYaml({ vaultName, model, provider = 'custom' }) {
  const ctx = 131072;
  const aux = {
    vision: 'qwen2.5-vl:7b', // fall back to same model if not present
    web_extract: model,
    compression: model,
    session_search: model,
    skills_hub: model,
    approval: model,
    mcp: model,
    flush_memories: model,
    title_generation: model,
  };
  const auxBlock = Object.entries(aux).map(([k, v]) =>
`  ${k}:
    model: ${v}
    provider: ${provider}
    base_url: ${OLLAMA_BASE_URL}
    api_key: sk-local-no-auth-needed
    context_length: ${ctx}`
  ).join('\n');

  return (
`# Hermes profile config — generated by codebook-to-profile.mjs
# Profile: ${vaultName}
# DO NOT edit by hand; regenerate via the bridge script.

model:
  default: ${model}
  provider: ${provider}
  base_url: ${OLLAMA_BASE_URL}
  api_key: sk-local-no-auth-needed
  context_length: ${ctx}

auxiliary:
${auxBlock}

session:
  prompt_cache: true           # hermes CLI reuses system prompt KV
  keep_last_n: -1              # unlimited turn retention in session
  fts5_index: true

memory:
  max_memory_chars: 2200
  max_user_chars: 1375
  enabled: true

gateway:
  enabled: false               # per-profile gateway off by default; turn on manually
`);
}

// ---------- .env generator ----------------------------------------------------
function envFile({ vaultName, agentUuid }) {
  return (
`# Hermes profile env — generated by codebook-to-profile.mjs
HERMES_HOME=${HERMES_HOME_ROOT}/${vaultName}
HERMES_PROFILE=${vaultName}
VAULT_HOME=${homedir()}/vaults/${vaultName}
COLLOQUY_AGENT_UUID=${agentUuid ?? ''}
OPENAI_BASE_URL=${OLLAMA_BASE_URL}
OPENAI_API_KEY=sk-local-no-auth-needed
OLLAMA_HOST=${OLLAMA_BASE_URL.replace('/v1', '').replace('http://', '')}
`);
}

// ---------- bridge one persona ------------------------------------------------
function bridge({ personaName, vaultName, agentUuid }) {
  const personaFile = findPersonaFile(personaName);
  if (!personaFile) throw new Error(`persona file not found for ${personaName}`);

  const md = readFileSync(personaFile, 'utf8');
  const profileDir = path.join(HERMES_HOME_ROOT, vaultName);
  mkdirSync(profileDir, { recursive: true });

  const model = MODEL_DEFAULTS[personaName] ?? 'qwen2.5:7b';

  const soulPath = path.join(profileDir, 'SOUL.md');
  writeFileSync(soulPath, extractSoul(md, vaultName));

  const cfgPath = path.join(profileDir, 'config.yaml');
  writeFileSync(cfgPath, configYaml({ vaultName, model }));

  const envPath = path.join(profileDir, '.env');
  writeFileSync(envPath, envFile({ vaultName, agentUuid }));

  return { vaultName, profileDir, model, soul: soulPath, config: cfgPath, env: envPath };
}

// ---------- main --------------------------------------------------------------
function arg(argv, name, def) {
  const i = argv.indexOf(name);
  return i >= 0 ? argv[i + 1] : def;
}

function main() {
  const argv = process.argv.slice(2);

  if (argv.includes('--all')) {
    const defaults = [
      { personaName: 'persona-voxel-v1',  vaultName: 'voxel'  },
      { personaName: 'persona-vertex-v1', vaultName: 'vertex' },
      // vectors are bridged individually with --agent-uuid
    ];
    const results = defaults.map(bridge);
    console.log(JSON.stringify(results, null, 2));
    return;
  }

  const personaName = arg(argv, '--persona');
  const vaultName   = arg(argv, '--vault');
  const agentUuid   = arg(argv, '--agent-uuid');
  if (!personaName || !vaultName) {
    console.error('usage: codebook-to-profile.mjs --persona <name> --vault <name> [--agent-uuid <uuid>]');
    console.error('       codebook-to-profile.mjs --all');
    process.exit(2);
  }
  console.log(JSON.stringify(bridge({ personaName, vaultName, agentUuid }), null, 2));
}

main();
