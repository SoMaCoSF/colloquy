#!/usr/bin/env node

/**
 * Colloquy Agent Worker
 * Listens for slurped spec files and auto-scaffolds code implementation.
 */

import fs from 'fs';
import path from 'path';
import { setupHarness, logError } from '../lib/logger.mjs';

setupHarness('AGENT-WORKER');

const args = process.argv.slice(2);
const docPath = args[0];

if (!docPath || !fs.existsSync(docPath)) {
  console.error('\x1b[31m[AGENT-WORKER] Missing or invalid doc path.\x1b[0m');
  process.exit(1);
}

console.log(`\x1b[36m🤖 [AGENT WORKER] Processing slurped spec: ${docPath}...\x1b[0m`);

const specContent = fs.readFileSync(docPath, 'utf8');
const titleMatch = specContent.match(/# Architecture Doc:\s*(.+)/);
const featureTitle = titleMatch ? titleMatch[1].trim() : 'Unassigned Feature';

const slug = path.basename(docPath, '.md');
const libModulePath = path.join(process.cwd(), 'lib', `${slug}.mjs`);

// Scaffold module code based on slurped specification
const moduleCode = `/**
 * Auto-generated by Colloquy Herdr Agent Worker
 * Feature: ${featureTitle}
 * Source Spec: ${docPath}
 * Generated At: ${new Date().toISOString()}
 */

export function executeFeature(context = {}) {
  console.log('[COLLOQUY MODULE] Executing: ${featureTitle}');
  return {
    status: 'EXECUTED',
    feature: '${featureTitle}',
    timestamp: Date.now(),
    context
  };
}
`;

fs.writeFileSync(libModulePath, moduleCode, 'utf8');
console.log(`\x1b[32m✔ [AGENT WORKER] Code scaffold generated at: lib/${slug}.mjs\x1b[0m`);

// Update the doc entry to reflect completed implementation
const updatedDoc = specContent + `\n## ⚡ Agent Implementation Status
- **Status:** Scaffolded & Implemented
- **Module Path:** \`lib/${slug}.mjs\`
- **Worker Session:** \`0x825-AGENT-WORKER\`
`;

fs.writeFileSync(docPath, updatedDoc, 'utf8');
